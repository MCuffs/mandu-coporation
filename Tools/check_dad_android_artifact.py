"""Inspect an actual APK/AAB. This never installs or runs the game and does not certify store approval."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import struct
import subprocess
import zipfile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('artifact', type=Path)
parser.add_argument('--android-player', type=Path, required=True)
parser.add_argument('--report', type=Path, required=True)
args = parser.parse_args()
checks = []

def check(name, passed, value):
    checks.append(dict(name=name, passed=bool(passed), value=value))

def elf_info(data):
    if data[:4] != b'\x7fELF' or data[4] != 2 or data[5] != 1:
        return dict(arm64=False, page16k=False, error='Not little-endian ELF64')
    machine = struct.unpack_from('<H', data, 18)[0]
    offset = struct.unpack_from('<Q', data, 32)[0]
    size, count = struct.unpack_from('<HH', data, 54)
    loads = []
    for i in range(count):
        pos = offset + i * size
        if struct.unpack_from('<I', data, pos)[0] != 1:
            continue
        file_offset, virtual = struct.unpack_from('<QQ', data, pos + 8)
        align = struct.unpack_from('<Q', data, pos + 48)[0]
        loads.append(dict(alignment=align, congruent16k=file_offset % 16384 == virtual % 16384))
    return dict(arm64=machine == 183, page16k=bool(loads) and all(p['alignment'] >= 16384 and p['congruent16k'] for p in loads), load_segments=loads)

def run(command):
    env = dict(os.environ, JAVA_HOME=str(args.android_player / 'OpenJDK'))
    result = subprocess.run([str(p) for p in command], capture_output=True, env=env, timeout=180)
    out = (result.stdout + result.stderr).decode('utf-8', errors='replace')
    if result.returncode:
        raise RuntimeError(out)
    return out

artifact = args.artifact.resolve()
is_apk = artifact.suffix.lower() == '.apk'
with zipfile.ZipFile(artifact) as archive:
    names = archive.namelist()
    native = {n: elf_info(archive.read(n)) for n in names if re.search(r'(^|/)lib/[^/]+/[^/]+\.so$', n)}
    architectures = sorted({n.split('/')[-2] for n in native})
    check('ARM64-only native payload exists', architectures == ['arm64-v8a'] and all(v['arm64'] for v in native.values()), architectures)
    check('Every native ELF LOAD segment supports 16KB alignment', bool(native) and all(v['page16k'] for v in native.values()), native)
    check('Player data exists', any('assets/bin/Data/' in n for n in names), len(names))

java = args.android_player / 'OpenJDK/bin/java.exe'
build_tools = args.android_player / 'SDK/build-tools'
versions = sorted((p for p in build_tools.iterdir() if p.is_dir() and (p / 'aapt2.exe').exists()), key=lambda p: tuple(int(n) for n in re.findall(r'\d+', p.name)))
tools = versions[-1]
if is_apk:
    manifest = run([tools / 'aapt2.exe', 'dump', 'badging', artifact])
    package = re.search(r"package: name='([^']+)'", manifest)
    target = re.search(r"targetSdkVersion:'(\d+)'", manifest)
    check('Final manifest has expected application ID', package and package[1] == 'com.manducorporation.dadwar', package[1] if package else manifest)
    check('Final manifest targets API36+', target and int(target[1]) >= 36, int(target[1]) if target else manifest)
    aligned = run([tools / 'zipalign.exe', '-c', '-P', '16', '-v', '4', artifact])
    check('APK zip alignment verifies for 16KB pages', 'Verification successful' in aligned, aligned.splitlines()[-1:])
    certificate = run([java, '-jar', tools / 'lib/apksigner.jar', 'verify', '--print-certs', artifact])
    check('APK cryptographic signature verifies', 'certificate' in certificate.lower(), certificate)
else:
    bundletool = next((args.android_player / 'Tools').glob('bundletool-all-*.jar'))
    manifest = run([java, '-jar', bundletool, 'dump', 'manifest', '--bundle=' + str(artifact), '--module=base'])
    check('Bundle manifest has expected application ID', 'package="com.manducorporation.dadwar"' in manifest, manifest)
    target = re.search(r'android:targetSdkVersion="(\d+)"', manifest)
    check('Bundle manifest targets API36+', target and int(target[1]) >= 36, int(target[1]) if target else manifest)
    validated = run([java, '-jar', bundletool, 'validate', '--bundle=' + str(artifact)])
    check('bundletool validates bundle structure', True, validated)

report = dict(artifact=str(artifact), sha256=hashlib.sha256(artifact.read_bytes()).hexdigest(), bytes=artifact.stat().st_size,
              status='ARTIFACT_CHECKS_PASS' if all(c['passed'] for c in checks) else 'FAIL', checks=checks,
              limits='Test artifacts may use a debug key. No device install, runtime test, production signing, APKs generated by Play or store approval is verified.')
args.report.parent.mkdir(parents=True, exist_ok=True)
args.report.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
for item in checks:
    print(('PASS ' if item['passed'] else 'FAIL ') + item['name'])
raise SystemExit(0 if all(c['passed'] for c in checks) else 1)
